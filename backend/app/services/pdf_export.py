"""PDF export for ClassMind AI (reportlab). Produces cleanly aligned A4 documents.

build_pdf(notes, transcript, chat=None, mode="full") -> bytes
  mode: "notes" | "transcript" | "full"
"""
import io
import os
from datetime import datetime
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.enums import TA_JUSTIFY, TA_LEFT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle
from reportlab.lib.units import mm
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.platypus import (
    HRFlowable,
    KeepTogether,
    ListFlowable,
    ListItem,
    PageBreak,
    Paragraph,
    SimpleDocTemplate,
    Spacer,
    Table,
    TableStyle,
)

NAVY = colors.HexColor("#0B2A4A")
BLUE = colors.HexColor("#2EA3F2")
LIGHT = colors.HexColor("#EAF4FD")
GREY = colors.HexColor("#5B6B7B")

# Prefer a Unicode font if available (handles accents, symbols); fall back to Helvetica.
FONT, FONT_B, FONT_I = "Helvetica", "Helvetica-Bold", "Helvetica-Oblique"
_DEJAVU = [
    ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
     "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
     "/usr/share/fonts/truetype/dejavu/DejaVuSans-Oblique.ttf"),
]
for regular, bold, italic in _DEJAVU:
    if all(os.path.exists(p) for p in (regular, bold, italic)):
        try:
            pdfmetrics.registerFont(TTFont("CM-Regular", regular))
            pdfmetrics.registerFont(TTFont("CM-Bold", bold))
            pdfmetrics.registerFont(TTFont("CM-Italic", italic))
            FONT, FONT_B, FONT_I = "CM-Regular", "CM-Bold", "CM-Italic"
        except Exception:
            pass
        break


def _styles():
    return {
        "title": ParagraphStyle("title", fontName=FONT_B, fontSize=22, leading=27, textColor=NAVY, spaceAfter=4),
        "meta": ParagraphStyle("meta", fontName=FONT, fontSize=9, leading=12, textColor=GREY, spaceAfter=10),
        "h1": ParagraphStyle("h1", fontName=FONT_B, fontSize=14, leading=18, textColor=NAVY, spaceBefore=14, spaceAfter=6),
        "h2": ParagraphStyle("h2", fontName=FONT_B, fontSize=11.5, leading=15, textColor=BLUE, spaceBefore=8, spaceAfter=3),
        "body": ParagraphStyle("body", fontName=FONT, fontSize=10.5, leading=15, alignment=TA_JUSTIFY, spaceAfter=4),
        "bullet": ParagraphStyle("bullet", fontName=FONT, fontSize=10.5, leading=15, alignment=TA_LEFT),
        "q": ParagraphStyle("q", fontName=FONT_B, fontSize=10.5, leading=14, textColor=NAVY, spaceBefore=4, spaceAfter=1),
        "a": ParagraphStyle("a", fontName=FONT, fontSize=10, leading=14, leftIndent=10, textColor=colors.HexColor("#222222"), spaceAfter=4),
        "cell": ParagraphStyle("cell", fontName=FONT, fontSize=10, leading=14),
        "cellb": ParagraphStyle("cellb", fontName=FONT_B, fontSize=10, leading=14, textColor=NAVY),
        "tx": ParagraphStyle("tx", fontName=FONT, fontSize=10, leading=15, alignment=TA_LEFT, spaceAfter=5),
        "foot": ParagraphStyle("foot", fontName=FONT_I, fontSize=8, leading=10, textColor=GREY),
    }


def _p(text, style):
    return Paragraph(escape(str(text or "")).replace("\n", "<br/>"), style)


def _bullets(items, st):
    return ListFlowable(
        [ListItem(_p(i, st["bullet"]), leftIndent=14, bulletColor=BLUE) for i in items if str(i).strip()],
        bulletType="bullet",
        start="•",
        leftIndent=14,
        bulletFontName=FONT_B,
        bulletFontSize=10,
    )


def _heading(text, st, level="h1"):
    parts = [Paragraph(escape(text), st[level])]
    if level == "h1":
        parts.append(HRFlowable(width="100%", thickness=0.8, color=BLUE, spaceBefore=0, spaceAfter=6))
    return parts


def _page_decor(title):
    def draw(canvas, doc):
        w, h = A4
        canvas.saveState()
        # header band
        canvas.setFillColor(NAVY)
        canvas.rect(0, h - 14 * mm, w, 14 * mm, stroke=0, fill=1)
        canvas.setFillColor(colors.white)
        canvas.setFont(FONT_B, 11)
        canvas.drawString(18 * mm, h - 9 * mm, "ClassMind")
        x = 18 * mm + canvas.stringWidth("ClassMind ", FONT_B, 11)
        canvas.setFillColor(BLUE)
        canvas.drawString(x, h - 9 * mm, "AI")
        canvas.setFillColor(colors.white)
        canvas.setFont(FONT, 8.5)
        canvas.drawRightString(w - 18 * mm, h - 9 * mm, (title or "")[:70])
        # footer
        canvas.setStrokeColor(colors.HexColor("#D5DEE7"))
        canvas.line(18 * mm, 14 * mm, w - 18 * mm, 14 * mm)
        canvas.setFillColor(GREY)
        canvas.setFont(FONT, 8)
        canvas.drawString(18 * mm, 9 * mm, "Generated by ClassMind AI - Turn every lecture into personalized learning")
        canvas.drawRightString(w - 18 * mm, 9 * mm, f"Page {doc.page}")
        canvas.restoreState()

    return draw


def _clock(sec) -> str:
    sec = int(sec or 0)
    h, rem = divmod(sec, 3600)
    m, s = divmod(rem, 60)
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m:02d}:{s:02d}"


def build_pdf(notes: dict, transcript: str, chat=None, mode: str = "full", meta=None, segments=None, bookmarks=None) -> bytes:
    meta = meta or {}
    st = _styles()
    notes = notes or {}
    title = notes.get("title") or "Lecture Notes"
    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf,
        pagesize=A4,
        leftMargin=18 * mm,
        rightMargin=18 * mm,
        topMargin=24 * mm,
        bottomMargin=22 * mm,
        title=title,
        author="ClassMind AI",
    )
    story = []
    stamp = datetime.now().strftime("%d %B %Y, %I:%M %p")
    doc_label = {"notes": "Study Notes", "transcript": "Lecture Transcript", "full": "Notes & Transcript"}.get(mode, "Notes")

    story.append(Paragraph(escape(title if mode != "transcript" else (title.replace("Lecture Notes", "Lecture Transcript"))), st["title"]))
    bits = [doc_label]
    if meta.get("course"):
        bits.append(escape(str(meta["course"])))
    bits.append(stamp)
    if meta.get("duration"):
        bits.append("Duration " + _clock(meta["duration"]))
    story.append(Paragraph(" &nbsp;|&nbsp; ".join(bits), st["meta"]))
    story.append(HRFlowable(width="100%", thickness=2, color=BLUE, spaceAfter=8))

    if mode in ("notes", "full"):
        if notes.get("summary"):
            box = Table([[_p(notes["summary"], st["body"])]], colWidths=[doc.width])
            box.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, -1), LIGHT),
                        ("LEFTPADDING", (0, 0), (-1, -1), 10),
                        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                        ("TOPPADDING", (0, 0), (-1, -1), 8),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
                        ("LINEBEFORE", (0, 0), (0, -1), 3, BLUE),
                    ]
                )
            )
            story += _heading("Summary", st) + [box]

        if notes.get("key_points"):
            story += _heading("Key Points", st) + [_bullets(notes["key_points"], st)]

        concepts = [c for c in notes.get("concepts", []) if c.get("term")]
        if concepts:
            story += _heading("Key Concepts", st)
            rows = [[Paragraph("Concept", st["cellb"]), Paragraph("Meaning", st["cellb"])]]
            for c in concepts:
                rows.append([_p(c["term"], st["cellb"]), _p(c.get("definition", ""), st["cell"])])
            t = Table(rows, colWidths=[doc.width * 0.27, doc.width * 0.73], repeatRows=1)
            t.setStyle(
                TableStyle(
                    [
                        ("BACKGROUND", (0, 0), (-1, 0), LIGHT),
                        ("LINEBELOW", (0, 0), (-1, 0), 1, BLUE),
                        ("LINEBELOW", (0, 1), (-1, -1), 0.4, colors.HexColor("#D5DEE7")),
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("TOPPADDING", (0, 0), (-1, -1), 5),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
                    ]
                )
            )
            story.append(t)

        sections = [s for s in notes.get("sections", []) if s.get("points")]
        if sections:
            story += _heading("Detailed Notes", st)
            for s in sections:
                block = [Paragraph(escape(s.get("heading", "")), st["h2"]), _bullets(s["points"], st), Spacer(1, 4)]
                story.append(KeepTogether(block[:2]))
                story.append(block[2])

        qs = [q for q in notes.get("practice_questions", []) if q.get("question")]
        if qs:
            story += _heading("Practice Questions", st)
            for i, q in enumerate(qs, 1):
                story.append(
                    KeepTogether(
                        [
                            Paragraph(f"Q{i}. {escape(q['question'])}", st["q"]),
                            Paragraph("<b>Answer:</b> " + escape(q.get("answer", "")), st["a"]),
                        ]
                    )
                )

        marks = [b for b in (bookmarks or []) if b.get("text")]
        if marks:
            story += _heading("Bookmarked Moments", st)
            for b in marks:
                stamp_txt = f"[{_clock(b['t'])}] " if b.get("t") is not None else ""
                story.append(Paragraph(f"<b>{stamp_txt}</b>{escape(b['text'])}", st["a"]))

        qa = [(m.get("role"), m.get("content", "")) for m in (chat or []) if m.get("content")]
        if qa:
            story += _heading("Student Q&A with ClassMind AI", st)
            for role, content in qa:
                if role == "user":
                    story.append(Paragraph("Q: " + escape(content), st["q"]))
                else:
                    story.append(_p(content, st["a"]))

    if mode in ("transcript", "full"):
        if mode == "full":
            story.append(PageBreak())
        story += _heading("Full Lecture Transcript", st)
        text = (transcript or "").strip()
        if not text:
            story.append(Paragraph("(No transcript recorded.)", st["body"]))
        elif segments and any(s.get("t") is not None for s in segments):
            rows = [
                [Paragraph(_clock(s["t"]), st["cellb"]), _p(s.get("text", ""), st["cell"])]
                for s in segments
                if s.get("text")
            ]
            tbl = Table(rows, colWidths=[16 * mm, doc.width - 16 * mm])
            tbl.setStyle(
                TableStyle(
                    [
                        ("VALIGN", (0, 0), (-1, -1), "TOP"),
                        ("TOPPADDING", (0, 0), (-1, -1), 3),
                        ("BOTTOMPADDING", (0, 0), (-1, -1), 3),
                        ("LINEBELOW", (0, 0), (-1, -1), 0.3, colors.HexColor("#E3E9EF")),
                    ]
                )
            )
            story.append(tbl)
        else:
            # split into readable paragraphs of ~4 sentences
            from ai_engine import split_sentences

            sents = split_sentences(text)
            for i in range(0, len(sents), 4):
                story.append(_p(" ".join(sents[i : i + 4]), st["tx"]))

    doc.build(story, onFirstPage=_page_decor(title), onLaterPages=_page_decor(title))
    return buf.getvalue()
